-- 2026-11-13 클론(ZAVAPASS-clone) 전용: 관리자 화면에서 쓰는데 클론 DB에 빠져 있던 것 4가지
--  ① interview_reports (실제 면접 후기) — 운영 DB와 같은 칸
--  ② approval_requests (권한 신청) — 운영 DB와 같은 칸
--  ③ admin_user_emails() — 관리자 화면에 면접자 아이디(로그인 이메일)를 붙임 (관리자만 결과 받음)
--  ④ admin_fix_answers(p_items) — 인식·발음 사전으로 지난 답변 글자를 한꺼번에 바로잡음 (점수는 그대로)
--  ⑤ submit_interview_report(p) — 후기 남기기·전화 후기 입력 (클론은 후기만 저장, 질문은 '후기 질문 정리'에서 질문은행으로 옮김)

-- ① 실제 면접 후기
create table if not exists public.interview_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  created_by uuid default auth.uid(),
  source text not null default 'self',
  person_name text,
  field_id text not null,
  org text,
  interview_date date,
  result text not null default 'waiting',
  format_note text,
  tips text,
  questions jsonb not null default '[]'::jsonb,
  added_count integer not null default 0,
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.interview_reports enable row level security;
drop policy if exists "interview_reports: 본인 읽기" on public.interview_reports;
create policy "interview_reports: 본인 읽기" on public.interview_reports for select to authenticated using (user_id = auth.uid() or created_by = auth.uid() or public.is_admin());
drop policy if exists "interview_reports: 관리자 고치기" on public.interview_reports;
create policy "interview_reports: 관리자 고치기" on public.interview_reports for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "interview_reports: 관리자 지우기" on public.interview_reports;
create policy "interview_reports: 관리자 지우기" on public.interview_reports for delete to authenticated using (public.is_admin());

-- ② 권한 신청
create table if not exists public.approval_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  field_id text not null,
  org text not null,
  memo text,
  proof_path text,
  status text not null default 'submitted',
  admin_note text,
  proof_deleted_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by uuid,
  created_at timestamptz not null default now(),
  interview_date date
);
alter table public.approval_requests enable row level security;
drop policy if exists "approval_requests: 본인" on public.approval_requests;
create policy "approval_requests: 본인" on public.approval_requests for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "approval_requests: 본인 신청" on public.approval_requests;
create policy "approval_requests: 본인 신청" on public.approval_requests for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "approval_requests: 관리자 처리" on public.approval_requests;
create policy "approval_requests: 관리자 처리" on public.approval_requests for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- ③ 면접자 아이디 (관리자만)
create or replace function public.admin_user_emails()
returns table(id uuid, email text)
language plpgsql security definer set search_path = public, auth
as $$
begin
  if not public.is_admin() then return; end if;
  return query select u.id, u.email::text from auth.users u;
end $$;
revoke all on function public.admin_user_emails() from public, anon;
grant execute on function public.admin_user_emails() to authenticated;

-- ④ 지난 답변 글자 바로잡기 (관리자만, 처음 받아 적은 글은 answer_raw에 남김)
create or replace function public.admin_fix_answers(p_items jsonb)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare it jsonb; n integer := 0; c integer;
begin
  if not public.is_admin() then raise exception '관리자만 할 수 있어요'; end if;
  for it in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) loop
    update public.interview_answers
       set answer_raw = coalesce(answer_raw, answer_text), answer_text = it->>'text', answer_fixed_at = now()
     where record_id = (it->>'record_id')::uuid and question_index = (it->>'question_index')::int
       and answer_text is distinct from it->>'text';
    get diagnostics c = row_count; n := n + c;
  end loop;
  return jsonb_build_object('updated', n);
end $$;
revoke all on function public.admin_fix_answers(jsonb) from public, anon;
grant execute on function public.admin_fix_answers(jsonb) to authenticated;

-- ⑤ 후기 남기기 · 전화 후기 입력
create or replace function public.submit_interview_report(p jsonb)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare v_id bigint; v_phone boolean := coalesce(p->>'source', 'self') = 'phone';
begin
  if auth.uid() is null then raise exception '로그인이 필요해요'; end if;
  if v_phone and not public.is_admin() then raise exception '관리자만 전화 후기를 넣을 수 있어요'; end if;
  if nullif(p->>'id', '') is not null then
    update public.interview_reports set
      field_id = coalesce(p->>'field_id', field_id), org = p->>'org', interview_date = nullif(p->>'interview_date', '')::date,
      result = coalesce(p->>'result', result), format_note = p->>'format_note', tips = p->>'tips',
      questions = coalesce(p->'questions', questions),
      person_name = case when v_phone then p->>'person_name' else person_name end,
      user_id = case when v_phone then nullif(p->>'user_id', '')::uuid else user_id end,
      updated_at = now()
     where id = (p->>'id')::bigint and (public.is_admin() or user_id = auth.uid() or created_by = auth.uid())
     returning id into v_id;
    if v_id is null then raise exception '고칠 수 있는 후기가 없어요'; end if;
  else
    insert into public.interview_reports(user_id, created_by, source, person_name, field_id, org, interview_date, result, format_note, tips, questions)
    values (case when v_phone then nullif(p->>'user_id', '')::uuid else auth.uid() end, auth.uid(), case when v_phone then 'phone' else 'self' end,
            p->>'person_name', coalesce(nullif(p->>'field_id', ''), 'public'), p->>'org', nullif(p->>'interview_date', '')::date,
            coalesce(p->>'result', 'waiting'), p->>'format_note', p->>'tips', coalesce(p->'questions', '[]'::jsonb))
    returning id into v_id;
  end if;
  return jsonb_build_object('id', v_id, 'added', 0, 'duplicate', 0);
end $$;
revoke all on function public.submit_interview_report(jsonb) from public, anon;
grant execute on function public.submit_interview_report(jsonb) to authenticated;
